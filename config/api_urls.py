"""URLs for the versioned REST API and its documentation.

`/api/schema/` is the raw OpenAPI document, generated by drf-spectacular.
`/api/docs/` is the human + agent-friendly portal served by apiwarden from
the committed spec file in `api-docs/`.
"""

from django.urls import include, path
from drf_spectacular.views import SpectacularAPIView
from rest_framework.routers import DefaultRouter

from links.api import (
    DashboardStatsView,
    LinkAnalyticsView,
    LinkViewSet,
    ProfileView,
    TokenView,
)

router = DefaultRouter()
router.register(r"links", LinkViewSet, basename="link")

urlpatterns = [
    path("v1/", include(router.urls)),
    path("v1/links/<str:code>/analytics/", LinkAnalyticsView.as_view()),
    path("v1/stats/", DashboardStatsView.as_view()),
    path("v1/me/", ProfileView.as_view()),
    path("v1/token/", TokenView.as_view(), name="token"),
    path("schema/", SpectacularAPIView.as_view(), name="schema"),
    path("docs/", include("apiwarden.urls"), name="docs"),
]
